source("R/pipeline.R")
dir.create("output", showWarnings = FALSE)
raw <- read.csv("data/raw_survey.csv", stringsAsFactors = FALSE, na.strings = c("", "NA"))
pop <- read.csv("data/population_sizes.csv", stringsAsFactors = FALSE)
res <- clean_survey(raw)
cl  <- add_weights(res$data, pop)
write.csv(cl, "output/clean_survey.csv", row.names = FALSE, na = "")
write.csv(res$flags, "output/dq_log.csv", row.names = FALSE)
summ <- res$flags |> count(rule, description, name = "rows_flagged")
write.csv(summ, "output/dq_summary.csv", row.names = FALSE)
truth <- jsonlite::read_json("data/ground_truth.json")
unw  <- mean(cl$employed_6mo == "Yes", na.rm = TRUE)
w_all  <- employment_rate(cl)
w_prog <- employment_rate(cl, "program_area")
w_prog$population_truth <- unlist(truth$by_program)[w_prog$group]
sink("output/analysis_output.txt")
cat("Rows in raw file:", nrow(raw), "| duplicate submissions removed:", nrow(res$removed), "| respondents kept:", nrow(cl), "\n\n")
cat("Rule violations (rows flagged, after duplicates removed)\n"); print(as.data.frame(summ), row.names = FALSE)
cat("\nEmployment within 6 months\n")
cat(sprintf("  Unweighted respondents : %.3f\n  Weighted by institution : %.3f (95%% CI %.3f to %.3f)\n  True population rate    : %.3f\n",
            unw, w_all$rate, w_all$lo, w_all$hi, truth$population_employment_rate))
cat("\nBy program area (weighted)\n"); print(transform(w_prog, rate = round(rate, 3), lo = round(lo, 3), hi = round(hi, 3), population_truth = round(population_truth, 3)), row.names = FALSE)
sink()
cat(readLines("output/analysis_output.txt"), sep = "\n")
